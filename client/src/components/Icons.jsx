// Avatar component
export function Avatar({ name, color, size = 32, style = {} }) {
  const COLORS = ["#2dd4bf","#f87171","#60a5fa","#a78bfa","#34d399","#fb923c","#f472b6","#facc15"];
  const bg = color || COLORS[(name?.charCodeAt(0) || 0) % COLORS.length];
  return (
    <div style={{
      width: size, height: size, borderRadius: "50%", background: bg,
      display: "flex", alignItems: "center", justifyContent: "center",
      fontSize: size * 0.36, fontWeight: 700, color: "#fff",
      flexShrink: 0, userSelect: "none", letterSpacing: "-.5px",
      ...style
    }}>
      {name?.slice(0, 2).toUpperCase()}
    </div>
  );
}

// Status dot
export function StatusDot({ status, style = {} }) {
  const colors = { online: "var(--online)", away: "var(--away)", offline: "var(--offline)" };
  return (
    <div style={{
      width: 9, height: 9, borderRadius: "50%",
      background: colors[status] || colors.offline,
      border: "2px solid var(--surface)",
      flexShrink: 0, ...style
    }} />
  );
}

// Tooltip wrapper
export function Tip({ children, label }) {
  return (
    <div style={{ position: "relative" }} title={label}>
      {children}
    </div>
  );
}
